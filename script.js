let navigationsVerlauf = [];

function zeigeKategorienUebersicht() {
  navigationsVerlauf = [];
  document.getElementById('back-btn').style.display = 'none';
  document.getElementById('home-btn').style.display = 'none';
  document.getElementById('search-container').style.display = 'block';

  let html = `
    <h2>Kategorie auswählen</h2>
    <div class="grid">
      <button class="btn kat-btn" onclick="zeigeHerstellerNachKategorie('buehne')">🚀 Arbeitsbühnen</button>
      <button class="btn kat-btn" onclick="zeigeHerstellerNachKategorie('stapler')">🚜 Stapler & Kettenbühnen</button>
    </div>
  `;
  document.getElementById('app').innerHTML = html;
}

function zeigeHerstellerNachKategorie(katId) {
  navigationsVerlauf.push({ typ: 'kategorie', wert: katId });
  document.getElementById('back-btn').style.display = 'block';
  document.getElementById('home-btn').style.display = 'block';

  const titel = katId === 'buehne' ? 'Arbeitsbühnen' : 'Stapler & Kettenbühnen';
  let html = `<h2>Hersteller (${titel})</h2><div class="grid">`;
  
  for (const key in portalDaten) {
    const hersteller = portalDaten[key];
    if (hersteller.kategorie === katId) {
      html += `
        <button class="btn hersteller-btn" style="border-left-color: ${hersteller.farbe}" onclick="waehleHersteller('${key}')">
          🏢 ${hersteller.name}
        </button>
      `;
    }
  }
  html += '</div>';
  document.getElementById('app').innerHTML = html;
}

function waehleHersteller(key) {
  navigationsVerlauf.push({ typ: 'hersteller', wert: key });
  document.getElementById('back-btn').style.display = 'block';
  document.getElementById('home-btn').style.display = 'block';
  
  const hersteller = portalDaten[key];
  let html = `<h2>${hersteller.name} - Modelle</h2><div class="grid">`;
  
  for (const maschine in hersteller.maschinen) {
    html += `
      <button class="btn maschine-btn" onclick="waehleMaschine('${key}', '${maschine}')">
        📦 ${maschine}
      </button>
    `;
  }
  html += '</div>';
  document.getElementById('app').innerHTML = html;
}

function waehleMaschine(herstellerKey, maschineKey) {
  navigationsVerlauf.push({ typ: 'maschine', hersteller: herstellerKey, maschine: maschineKey });
  
  const dokumente = portalDaten[herstellerKey].maschinen[maschineKey];
  let html = `<h2>${portalDaten[herstellerKey].name} ${maschineKey}</h2><div class="grid">`;
  
  if (!dokumente || dokumente.length === 0) {
    html += '<p>Keine Dokumente für diese Maschine hinterlegt.</p>';
  } else {
    dokumente.forEach(doku => {
      // Nutzt jetzt die maschine-btn Klasse für das einheitliche gelbe Design
      html += `
        <button class="btn maschine-btn" onclick="oeffnePdf('${doku.datei}', '${doku.titel}')">
          ${doku.titel}
        </button>
      `;
    });
  }
  html += '</div>';
  document.getElementById('app').innerHTML = html;
}

